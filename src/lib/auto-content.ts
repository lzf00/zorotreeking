/**
 * 「自动生成」内容的统一判定与说法（第 210 轮）。
 *
 * 现状（2026-11-26 实测）：193 篇 AI 日报 + 23 篇周报里，173 + 23 篇正文**没有任何**
 * 说明，读者只能从一个标签 chip「auto」猜；而结构化数据里 author 一律写着
 * `Person: Zifei Liu` —— 机器整理的文字被标成个人署名。投资站的复盘有正文声明，
 * 但同样在 JSON-LD 里署了人名。
 *
 * 这里只做两件事：
 *   1. 判定一篇内容是不是自动产出（按路径/标签，不猜正文措辞）；
 *   2. 给出中英各一句**固定说法**，模板直接用，避免每篇各写一版。
 *
 * 判定依据是**结构**而不是文字：路径前缀 + frontmatter 标签。加新流水线时
 * 在 AUTO_RULES 里加一行即可，不用去改 193 个 mdx。
 */
export type AutoKind = "digest" | "recap" | "weekly";

type Rule = { prefix: string; kind: AutoKind };

/**
 * 顺序有意义：先匹配更具体的担。
 * `/invest/digest-` 与 `/invest/market-recap-` 都属于投资站的自动化数据流，
 * 但读者关心的是"这是抓取/生成的"，两种措辞略有差别。
 */
export const AUTO_RULES: Rule[] = [
  { prefix: "/invest/market-recap-", kind: "recap" },
  { prefix: "/en/invest/market-recap-", kind: "recap" },
  { prefix: "/invest/digest-", kind: "digest" },
  { prefix: "/en/invest/digest-", kind: "digest" },
  { prefix: "/ai/digest-", kind: "digest" },
  { prefix: "/en/ai/digest-", kind: "digest" },
  { prefix: "/ai/weekly-", kind: "weekly" },
  { prefix: "/en/ai/weekly-", kind: "weekly" },
];

/** 按 URL 路径判定；不是自动产出的返回 null */
export function autoKindOfPath(pathname: string): AutoKind | null {
  const clean = pathname.replace(/index\.html$/, "");
  for (const rule of AUTO_RULES) {
    if (clean.startsWith(rule.prefix)) return rule.kind;
  }
  return null;
}

/** 按 frontmatter 判定（列表页/首页这类拿不到最终 URL 的地方用） */
export function autoKindOfPost(post: {
  translationKey?: string;
  tags?: readonly string[];
}): AutoKind | null {
  const tags = post.tags ?? [];
  const key = post.translationKey ?? "";
  if (tags.includes("market-recap") || key.startsWith("market-recap-")) return "recap";
  if (tags.includes("digest") || key.startsWith("digest-")) return "digest";
  if (key.startsWith("weekly-")) return "weekly";
  // `auto` 是内容流水线打的宽标签（日报/周报都有），兜底认它
  if (tags.includes("auto")) return "digest";
  return null;
}

export type AutoCopy = { label: string; text: string };

/** 固定说法：一句话说清"谁生成的、能信到什么程度" */
export function autoDisclosure(kind: AutoKind, lang: "zh" | "en" = "zh"): AutoCopy {
  const zh: Record<AutoKind, AutoCopy> = {
    digest: {
      label: "自动整理",
      text: "本页由脚本抓取公开资讯并自动整理（含 AI 改写），不是人工撰写。数字与措辞都可能有误，请以原始来源为准。",
    },
    recap: {
      label: "自动生成",
      text: "本页由脚本抓取行情数据自动生成，不是人工撰写。行情数字以交易所与数据源为准，不构成投资建议。",
    },
    weekly: {
      label: "自动汇总",
      text: "本页由脚本汇总本周的产出自动生成，不是人工撰写。条目取舍由规则决定，可能漏掉你认为重要的事。",
    },
  };
  const en: Record<AutoKind, AutoCopy> = {
    digest: {
      label: "Auto-curated",
      text: "This page is assembled by a script from public news feeds (with AI rewriting), not written by hand. Numbers and wording may be wrong; trust the original sources.",
    },
    recap: {
      label: "Auto-generated",
      text: "This page is generated by a script from market data, not written by hand. Figures follow the exchanges and data vendors. Not investment advice.",
    },
    weekly: {
      label: "Auto-summarised",
      text: "This page is generated by a script that summarises the week's output, not written by hand. Rules decide what is included, so it may miss what you care about.",
    },
  };
  return (lang === "en" ? en : zh)[kind];
}
